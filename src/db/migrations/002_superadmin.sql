CREATE INDEX IF NOT EXISTS idx_institutions_is_active  ON public.institutions(is_active);
CREATE INDEX IF NOT EXISTS idx_institutions_created_at ON public.institutions(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_users_institution_role  ON public.users(institution_id, role);

-- ---------------------------------------------------------------------------
-- 5. RLS policies — protect direct Supabase dashboard access
--    (Note: backend uses service_role_key which bypasses RLS;
--     these policies protect against direct anon/authenticated key access)
-- ---------------------------------------------------------------------------

-- Superadmin audit log: only superadmins can read
ALTER TABLE public.superadmin_audit_log ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "superadmin_audit_log_access" ON public.superadmin_audit_log;
CREATE POLICY "superadmin_audit_log_access"
  ON public.superadmin_audit_log
  FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.users
      WHERE id   = auth.uid()
        AND role = 'superadmin'
    )
  );

-- Institutions: superadmins can see all; admin/teacher/student only their own
ALTER TABLE public.institutions ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "institutions_superadmin"   ON public.institutions;
DROP POLICY IF EXISTS "institutions_own_tenant"   ON public.institutions;

CREATE POLICY "institutions_superadmin"
  ON public.institutions FOR ALL
  USING (
    EXISTS (
      SELECT 1 FROM public.users
      WHERE id = auth.uid() AND role = 'superadmin'
    )
  );

CREATE POLICY "institutions_own_tenant"
  ON public.institutions FOR SELECT
  USING (
    EXISTS (
      SELECT 1 FROM public.users
      WHERE id             = auth.uid()
        AND institution_id = institutions.id
    )
  );

-- ---------------------------------------------------------------------------
-- 6. Helper function: is the calling user a superadmin?
--    (Useful for RLS policies on future tables)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.is_superadmin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.users
    WHERE id = auth.uid() AND role = 'superadmin'
  );
$$;

