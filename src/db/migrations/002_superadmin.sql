-- ---------------------------------------------------------------------------
-- 3. Superadmin audit log — tracks every cross-tenant action
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.superadmin_audit_log (
  id            UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  actor_id      UUID        NOT NULL REFERENCES public.users(id) ON DELETE SET NULL,
  action        TEXT        NOT NULL,          -- e.g. 'DISABLE_INSTITUTION', 'CHANGE_ROLE'
  target_type   TEXT        NOT NULL,          -- 'institution' | 'user' | 'course'
  target_id     UUID,
  payload       JSONB,                         -- before/after snapshot
  ip_address    INET,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_audit_log_actor      ON public.superadmin_audit_log(actor_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_target     ON public.superadmin_audit_log(target_type, target_id);
CREATE INDEX IF NOT EXISTS idx_audit_log_created_at ON public.superadmin_audit_log(created_at DESC);

-- ---------------------------------------------------------------------------
-- 4. Performance indexes for cross-tenant queries (superadmin list views)
