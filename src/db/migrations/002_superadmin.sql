-- ---------------------------------------------------------------------------
-- 1. Add 'superadmin' to the role CHECK constraint on public.users
-- ---------------------------------------------------------------------------
DO $$
DECLARE
  con_name TEXT;
BEGIN
  -- Find the role check constraint name (auto-generated by Supabase)
  SELECT conname INTO con_name
  FROM pg_constraint
  WHERE conrelid = 'public.users'::regclass
    AND contype   = 'c'
    AND pg_get_constraintdef(oid) ILIKE '%role%';

  IF con_name IS NOT NULL THEN
    EXECUTE format('ALTER TABLE public.users DROP CONSTRAINT %I', con_name);
  END IF;
END $$;

ALTER TABLE public.users
  ADD CONSTRAINT users_role_check
  CHECK (role IN ('student', 'teacher', 'admin', 'superadmin'));

-- Also update profiles table if it exists
DO $$
DECLARE
  con_name TEXT;
BEGIN
  SELECT conname INTO con_name
  FROM pg_constraint
  WHERE conrelid = 'public.profiles'::regclass
    AND contype   = 'c'
    AND pg_get_constraintdef(oid) ILIKE '%role%';

  IF con_name IS NOT NULL THEN
    EXECUTE format('ALTER TABLE public.profiles DROP CONSTRAINT %I', con_name);
    ALTER TABLE public.profiles
      ADD CONSTRAINT profiles_role_check
      CHECK (role IN ('student', 'teacher', 'admin', 'superadmin'));
  END IF;
EXCEPTION WHEN undefined_table THEN
  NULL; -- profiles table doesn't exist, skip
END $$;

